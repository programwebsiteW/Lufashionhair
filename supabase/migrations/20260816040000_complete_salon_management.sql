create or replace function public.preparar_agendamento()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  inicio_novo timestamp;
  fim_novo timestamp;
begin
  if new.cliente_id is not null then
    select c.nome into new.cliente_nome
    from public.clientes c
    where c.id = new.cliente_id and c.owner_id = new.owner_id;
  else
    new.cliente_nome := public.formatar_nome(new.cliente_nome);
  end if;

  if new.servico_id is not null and (tg_op = 'INSERT' or new.servico_id is distinct from old.servico_id) then
    select s.nome, s.duracao_minutos, s.preco
      into new.servico_nome, new.duracao_minutos, new.valor_servico
    from public.servicos s
    where s.id = new.servico_id and s.owner_id = new.owner_id;
  end if;

  new.updated_at := now();

  if new.status not in ('cancelado','faltou') then
    inicio_novo := new.data + new.hora;
    fim_novo := inicio_novo + make_interval(mins => new.duracao_minutos);
    if exists (
      select 1
      from public.agendamentos a
      where a.owner_id = new.owner_id
        and a.id <> coalesce(new.id, 0)
        and a.status not in ('cancelado','faltou')
        and tsrange(a.data + a.hora, a.data + a.hora + make_interval(mins => a.duracao_minutos), '[)')
            && tsrange(inicio_novo, fim_novo, '[)')
    ) then
      raise exception 'Esse horario conflita com outro atendimento. Escolha outro horario.';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists agendamentos_preparar_trg on public.agendamentos;
create trigger agendamentos_preparar_trg
before insert or update on public.agendamentos
for each row execute function public.preparar_agendamento();

create or replace function public.sincronizar_pagamento_agendamento()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  insert into public.pagamentos (owner_id, agendamento_id, valor_servico)
  values (new.owner_id, new.id, coalesce(new.valor_servico, 0))
  on conflict (agendamento_id) do update
    set valor_servico = excluded.valor_servico,
        updated_at = now()
    where public.pagamentos.valor_pago = 0;
  return new;
end;
$$;

drop trigger if exists agendamentos_pagamento_trg on public.agendamentos;
create trigger agendamentos_pagamento_trg
after insert or update of valor_servico, servico_id on public.agendamentos
for each row execute function public.sincronizar_pagamento_agendamento();

create or replace function public.preparar_pagamento()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  total numeric(10,2);
begin
  total := greatest(new.valor_servico - new.desconto, 0);
  if new.valor_pago <= 0 then
    new.status := 'pendente';
    new.data_pagamento := null;
    new.forma_pagamento := null;
  elsif new.valor_pago < total then
    new.status := 'parcial';
    new.data_pagamento := coalesce(new.data_pagamento, current_date);
  else
    new.status := 'pago';
    new.valor_pago := total;
    new.data_pagamento := coalesce(new.data_pagamento, current_date);
  end if;
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists pagamentos_preparar_trg on public.pagamentos;
create trigger pagamentos_preparar_trg
before insert or update on public.pagamentos
for each row execute function public.preparar_pagamento();

create or replace function public.refletir_cliente_agendamentos()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.nome is distinct from old.nome then
    update public.agendamentos
    set cliente_nome = new.nome, updated_at = now()
    where owner_id = new.owner_id and cliente_id = new.id;
  end if;
  return new;
end;
$$;

drop trigger if exists clientes_refletir_trg on public.clientes;
create trigger clientes_refletir_trg
after update of nome on public.clientes
for each row execute function public.refletir_cliente_agendamentos();

create or replace function public.refletir_servico_agendamentos()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.nome is distinct from old.nome
     or new.duracao_minutos is distinct from old.duracao_minutos
     or new.preco is distinct from old.preco then
    update public.agendamentos
    set servico_nome = new.nome,
        duracao_minutos = new.duracao_minutos,
        valor_servico = new.preco,
        updated_at = now()
    where owner_id = new.owner_id
      and servico_id = new.id
      and data >= current_date
      and status in ('agendado','confirmado','em_andamento');
  end if;
  return new;
end;
$$;

drop trigger if exists servicos_refletir_trg on public.servicos;
create trigger servicos_refletir_trg
after update of nome, duracao_minutos, preco on public.servicos
for each row execute function public.refletir_servico_agendamentos();

