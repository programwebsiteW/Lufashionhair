-- Completa o sistema da Lu Fashion Hair sem apagar os dados existentes.

create extension if not exists pg_cron with schema pg_catalog;

alter table public.clientes
  add column if not exists deleted_at timestamptz;

update public.clientes
set deleted_at = coalesce(deleted_at, updated_at, now())
where ativo = false and deleted_at is null;

alter table public.agendamentos
  add column if not exists duracao_minutos integer not null default 60
    check (duracao_minutos between 15 and 1440),
  add column if not exists valor_servico numeric(10,2)
    check (valor_servico is null or valor_servico >= 0);

update public.agendamentos a
set duracao_minutos = s.duracao_minutos,
    valor_servico = coalesce(a.valor_servico, s.preco)
from public.servicos s
where a.servico_id = s.id;

create table if not exists public.pagamentos (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  agendamento_id bigint not null unique references public.agendamentos(id) on delete cascade,
  valor_servico numeric(10,2) not null default 0 check (valor_servico >= 0),
  desconto numeric(10,2) not null default 0 check (desconto >= 0),
  valor_pago numeric(10,2) not null default 0 check (valor_pago >= 0),
  status text not null default 'pendente' check (status in ('pendente','parcial','pago')),
  forma_pagamento text check (forma_pagamento is null or forma_pagamento in ('pix','dinheiro','debito','credito','transferencia','outro')),
  data_pagamento date,
  observacoes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

insert into public.pagamentos (owner_id, agendamento_id, valor_servico)
select a.owner_id, a.id, coalesce(a.valor_servico, 0)
from public.agendamentos a
on conflict (agendamento_id) do nothing;

create table if not exists public.despesas (
  id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  descricao text not null check (char_length(trim(descricao)) between 1 and 255),
  categoria text not null default 'outros' check (categoria in ('produtos','materiais','aluguel','energia','agua','internet','transporte','manutencao','outros')),
  valor numeric(10,2) not null check (valor > 0),
  data date not null default current_date,
  pago boolean not null default true,
  observacoes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.formatar_nome(valor text)
returns text
language sql
immutable
strict
set search_path = ''
as $$
  select initcap(lower(regexp_replace(trim(valor), '\s+', ' ', 'g')));
$$;

create or replace function public.preparar_cliente()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.nome := public.formatar_nome(new.nome);
  if new.deleted_at is null then
    new.ativo := true;
  else
    new.ativo := false;
  end if;
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists clientes_preparar_trg on public.clientes;
create trigger clientes_preparar_trg
before insert or update on public.clientes
for each row execute function public.preparar_cliente();

